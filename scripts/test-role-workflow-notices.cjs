const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const loaded = { exports: {} };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/role-workflow-notices.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { module: loaded, exports: loaded.exports });
const notices = loaded.exports.getRoleWorkflowNotices;
const characteristics = [{ created_at: '2026-09-01T00:00:00Z', updated_at: '2026-09-10T00:00:00Z' }];
assert.match(notices({ characteristics: [] }).competencies, /No competencies/);
assert.match(notices({ characteristics: [] }).composite, /Add competencies first/);
assert.equal(notices({ characteristics }).competencies, null);
assert.match(notices({ characteristics }).composite, /Not generated/);
const old = { created_at: '2026-09-05T00:00:00Z' };
assert.match(notices({ characteristics, composite: old }).competencies, /have changed/);
assert.match(notices({ characteristics, composite: old }).composite, /Update needed/);
const replacement = { ...old, storage_path: `org/roles/role/${Date.parse('2026-09-12T00:00:00Z')}-role.docx` };
assert.equal(notices({ characteristics, composite: replacement }).competencies, null);
assert.equal(notices({ characteristics, composite: replacement }).composite, null);
assert.match(notices({ characteristics: [], composite: replacement }).composite, /Update needed/);
assert.equal(notices({ characteristics, composite: { created_at: '2026-09-12T00:00:00Z' } }).composite, null);
console.log('Passed: missing competencies, missing composite, changed competencies, replacement composite, and removed competencies.');
